// Exports YouTube/Google cookies as a Netscape-format cookies.txt using the
// official chrome.cookies API (the same mechanism extensions like
// "Get cookies.txt LOCALLY" use) — no file-system access to the browser's
// own (locked) cookie database.

const DOMAINS = ["youtube.com", "google.com"];
const statusEl = document.getElementById("status");

function toNetscapeLine(c) {
  const domain = c.domain.startsWith(".") ? c.domain : (c.hostOnly ? c.domain : "." + c.domain);
  const includeSubdomains = domain.startsWith(".") ? "TRUE" : "FALSE";
  const path = c.path || "/";
  const secure = c.secure ? "TRUE" : "FALSE";
  const expiry = c.session ? "0" : String(Math.round(c.expirationDate || 0));
  return [domain, includeSubdomains, path, secure, expiry, c.name, c.value].join("\t");
}

document.getElementById("export").addEventListener("click", async () => {
  statusEl.textContent = "Đang đọc cookies…";
  try {
    const all = [];
    for (const domain of DOMAINS) {
      all.push(...await chrome.cookies.getAll({ domain }));
    }
    const seen = new Set();
    const uniq = all.filter((c) => {
      const key = c.domain + "|" + c.path + "|" + c.name;
      if (seen.has(key)) return false;
      seen.add(key);
      return true;
    });
    if (uniq.length === 0) {
      statusEl.textContent = "Không tìm thấy cookie nào của youtube.com/google.com. Hãy đăng nhập YouTube rồi thử lại.";
      return;
    }
    const lines = [
      "# Netscape HTTP Cookie File",
      "# https://curl.se/docs/http-cookies.html",
      "# Generated by ChatOverlay Cookie Export — do not share this file, it contains your login session.",
      "",
      ...uniq.map(toNetscapeLine),
      "",
    ];
    const blob = new Blob([lines.join("\n")], { type: "text/plain" });
    const url = URL.createObjectURL(blob);
    chrome.downloads.download({ url, filename: "cookies.txt", saveAs: true }, (downloadId) => {
      if (chrome.runtime.lastError || downloadId === undefined) {
        statusEl.textContent = "Lỗi: " + (chrome.runtime.lastError?.message || "không lưu được file.");
      } else {
        statusEl.textContent = `Đã lưu ${uniq.length} cookie vào cookies.txt.`;
      }
      URL.revokeObjectURL(url);
    });
  } catch (e) {
    statusEl.textContent = "Lỗi: " + e.message;
  }
});
